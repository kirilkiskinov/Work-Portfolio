# Въвеждане на трицифрено число
m = int(input("Въведете трицифрено число: "))

# Проверка дали числото е трицифрено
if 100 <= m <= 999:
    # Получаване на отделните цифри
    stotici = m // 100
    desetici = (m // 10) % 10
    edinici = m % 10

    # Логически израз за проверка дали поне две от цифрите са равни
    pone_dve_ravni = (stotici == desetici) or (stotici == edinici) or (desetici == edinici)

    # Извеждане на резултата
    if pone_dve_ravni:
        print("Поне две от цифрите на числото са равни.")
    else:
        print("Няма еднакви цифри в числото.")
else:
    print("Моля, въведете валидно трицифрено число.")
