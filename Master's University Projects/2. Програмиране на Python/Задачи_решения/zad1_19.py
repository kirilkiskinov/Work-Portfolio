# Брой на членовете от редицата
n = 20

# Първите два члена на редицата Фибоначи
fib = [1, 1]

# Изчисляваме останалите членове на редицата до 20-тия член
for i in range(2, n):
    next_member = fib[i-1] + fib[i-2]
    fib.append(next_member)

# Извеждане на първите 20 члена
print("Първите 20 члена на редицата на Фибоначи са:")
print(fib)

# Изчисляване на средната стойност
average = sum(fib) / n

# Извеждане на средната стойност
print(f"Средната стойност на първите 20 члена е: {average}")
