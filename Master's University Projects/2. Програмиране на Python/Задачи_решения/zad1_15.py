# Използване на цикъл for
print("Числата от 1 до 20 с for цикъл:")
for i in range(1, 21):
    print(i, end=' ')  # end=' ' извежда числата на един ред, разделени с интервал
print()  # нов ред

# Използване на цикъл while
print("Числата от 1 до 20 с while цикъл:")
i = 1
while i <= 20:
    print(i, end=' ')  # end=' ' извежда числата на един ред, разделени с интервал
    i += 1  # увеличаваме i с 1
