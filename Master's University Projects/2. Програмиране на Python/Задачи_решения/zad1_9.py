# Въвеждане на трицифрено число
m = int(input("Въведете трицифрено число: "))

# Проверка дали числото е трицифрено
if 100 <= m <= 999:
    # Получаване на отделните цифри
    stotici = m // 100
    desetici = (m // 10) % 10
    edinici = m % 10

    # Логически израз за проверка дали всички цифри са различни
    razlichni_cifri = (stotici != desetici) and (stotici != edinici) and (desetici != edinici)

    # Извеждане на резултата
    if razlichni_cifri:
        print("Цифрите на числото са различни.")
    else:
        print("Цифрите на числото не са различни.")
else:
    print("Моля, въведете валидно трицифрено число.")
