# Въвеждане на трицифрено число
num = int(input("Въведете трицифрено цяло число: "))

# Проверка дали числото е трицифрено
if 100 <= num <= 999:
    # Получаване на цифрите
    desetici = (num // 10) % 10  # Втората цифра (десетици)
    edinici = num % 10           # Третата цифра (единици)
    stotici = num // 100         # Първата цифра (стотици)

    # Логически израз за проверка на наличието на цифрата 7
    is_correct = (stotici == 7) or (desetici == 7) or (edinici == 7)

    # Извеждане на резултата
    if is_correct:
        print("Поне една от цифрите на числото е равна на 7.")
    else:
        print("Нито една от цифрите на числото не е равна на 7.")
else:
    print("Числото, което сте въвели, не е трицифрено.")
