def quadratic_value(a, b, c, x):
    # Изчисляваме стойността на квадратното уравнение
    return a * x**2 + b * x + c

# Основен цикъл за изчисляване на различни уравнения
while True:
    print("Изчисляване на стойността на квадратно уравнение a*x^2 + b*x + c")
    
    # Въвеждане на коефициентите и стойността на x от потребителя
    a = float(input("Въведете коефициент a: "))
    b = float(input("Въведете коефициент b: "))
    c = float(input("Въведете коефициент c: "))
    x = float(input("Въведете стойност за x: "))
    
    # Изчисляваме стойността на уравнението и я отпечатваме
    result = quadratic_value(a, b, c, x)
    print(f"Стойността на уравнението {a}*x^2 + {b}*x + {c} за x = {x} е: {result}")
    
    # Въпрос за продължаване
    cont = input("Искате ли да изчислите друга стойност? (да/не): ").strip().lower()
    if cont != "да":
        break
    # Примери: 
    # а = 1 , b = 3 , c = -4, x = 1    D > 0
    # а = 1 , b = 4 , c = 4 , x = 1    D == 0
    # а = 1 , b = 2 , c = 5 , x = 1    D < 0
