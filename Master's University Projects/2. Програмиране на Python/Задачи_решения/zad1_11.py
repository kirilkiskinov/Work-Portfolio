# Въвеждане на години, разделени със запетая
years = input("Въведете години, разделени със запетая: ").split(',')

# Функция за проверка дали дадена година е високосна
def is_leapyear(year):
    year = int(year)
    # Условия за високосна година:
    # - Годината се дели на 4 без остатък, но не и на 100 ИЛИ
    # - Годината се дели на 400 без остатък
    return (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0)

# Обхождане на всички въведени години и проверка дали са високосни
for year in years:
    year = year.strip()  # Премахване на излишни интервали
    if is_leapyear(year):
        print(f"{year} е високосна година.")
    else:
        print(f"{year} не е високосна година.")
